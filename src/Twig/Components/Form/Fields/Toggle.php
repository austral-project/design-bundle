namespace Austral\DesignBundle\Twig\Components\Form\Fields;

use Symfony\UX\TwigComponent\Attribute\AsTwigComponent;
use Symfony\UX\TwigComponent\Attribute\PostMount;
use Symfony\UX\TwigComponent\Attribute\PreMount;

#[AsTwigComponent('Austral:Form:Fields:Toggle', template: '@AustralDesign/Twig/Components/Form/Fields/toggle.html.twig')]
final class Toggle extends Input
{
  public string $type = 'checkbox';

  /**
   * @param array<string, mixed> $data
   *
   * @return array<string, mixed>
   */
  #[PreMount]
  public function preMount(array $data): array
  {
    return parent::preMount($data);
  }

  /**
   * @param array<string, mixed> $data
   *
   * @return array<string, mixed>
   */
  #[PostMount]
  public function postMount(array $data): array
  {
    $this->type = 'checkbox';

    return parent::postMount($data);
  }
}
