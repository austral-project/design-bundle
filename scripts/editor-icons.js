// Generates src/Resources/assets/components/form/fields/textarea/wysiwyg/icons.js: the pictos of the editor, inlined from
// src/Resources/public/austral-picto so the whole set is not loaded. Run with "npm run icons".

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const PICTOS = path.join(ROOT, "src/Resources/public/austral-picto");
const TARGET = path.join(ROOT, "src/Resources/assets/components/form/fields/textarea/wysiwyg/icons.js");

// Pictos of the default toolbar of the Wysiwyg field (austral/form-bundle) and of the editor itself.
const NAMES = [
  "align-center", "align-justify", "align-left", "align-right", "bold", "code", "content-left",
  "corner-forward", "corner-rearward", "indent-less", "indent-more", "italic", "link", "link-2", "list-ol",
  "list-ul", "maximize", "minimize", "minus", "strike", "superior", "underline"
];

const clean = (svg) => svg
  .replace(/<!--[\s\S]*?-->/g, "")
  .replace(/<title>[\s\S]*?<\/title>/g, "")
  .replace(/\s+/g, " ")
  .replace(/>\s+</g, "><")
  .replace(/<svg /, '<svg aria-hidden="true" focusable="false" fill="currentColor" ')
  .trim();

const icons = {};
NAMES.forEach((name) => {
  const file = path.join(PICTOS, name + ".svg");
  if(!fs.existsSync(file)) {
    throw new Error("Picto not found: " + file);
  }
  icons[name] = clean(fs.readFileSync(file, "utf8"));
});

const header = fs.readFileSync(__filename, "utf8").split("\n").slice(0, 8).join("\n");
fs.writeFileSync(TARGET, header + "\n\n// Generated by scripts/editor-icons.js: do not edit.\n" +
  "export default " + JSON.stringify(icons, null, 2) + ";\n");
console.log("editor-icons: " + NAMES.length + " pictos -> " + path.relative(ROOT, TARGET));
